import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
const read=path=>fs.readFileSync(new URL("../"+path,import.meta.url),"utf8");
test("Both audiences use exactly one preview source without duplicating issue authority",()=>{
 const merchant=read("app/(dashboard)/dashboard/invoice/[id]/page.tsx");
 const client=read("app/(dashboard)/dashboard/invoice/[id]/client-preview/page.tsx");
 const source=read("src/features/invoices/lib/audience-preview.ts");
 const renderer=read("src/features/invoices/sections/InvoiceDocumentPreviewSection.tsx");
 assert.match(merchant,/buildAudiencePreviewDraft\(invoice,settings\.businessName\)/);
 assert.match(client,/buildAudiencePreviewDraft\(invoice,settings\.businessName\)/);
 assert.match(merchant,/<InvoiceDocumentPreviewSection/);
 assert.match(client,/<InvoiceDocumentPreviewSection/);
 assert.match(source,/formatDocumentNumber/);
 assert.match(source,/record\.amount/);
 assert.match(source,/record\.date/);
 assert.match(source,/record\.dueDate/);
 assert.match(renderer,/draft-preview-watermark/);
 assert.match(renderer,/DRAFT — NOT ISSUED/);
});
test("Payment actions differ by audience and are fail-closed for every Preview",()=>{
 const actions=read("src/features/invoices/components/InvoiceAudienceToolbar.tsx");
 assert.match(actions,/Merchant Facing/);
 assert.match(actions,/Client Facing/);
 assert.match(actions,/Send Reminder/);
 assert.match(actions,/Revalidate/);
 assert.match(actions,/Copy Client Link/);
 assert.match(actions,/Download/);
 assert.match(actions,/Print Invoice/);
 assert.match(actions,/Report Transfer/);
 assert.match(actions,/Check Payment/);
 assert.match(actions,/Pay Now/);
 assert.match(actions,/type="button" disabled/);
 assert.match(actions,/No NRS-issued IRN\/QR/);
 assert.match(actions,/No verified account/);
 assert.doesNotMatch(actions,/window\.print|navigator\.clipboard|fetch\(|localStorage|sessionStorage|createObjectURL/);
});
test("Client-facing demo stays on merchant workspace path, not a public issued document",()=>{
 const route=read("app/(dashboard)/dashboard/invoice/[id]/client-preview/page.tsx");
 const lifecycle=read("src/features/invoices/lib/document-lifecycle.ts");
 assert.match(route,/Client-Facing PREVIEW within the merchant workspace/);
 assert.match(route,/No link is sent/);
 assert.match(route,/merchantPayment\(settings\)/);
 assert.match(route,/invoiceAppearance\.template/);
 assert.match(lifecycle,/PREVIEW_ISSUANCE_EVIDENCE/);
 assert.match(lifecycle,/recorded:false,authorized:false,immutableSnapshot:false/);
});
